  const supported = ['zh-CN', 'en-US'];
  const storageKey = 'catalogflow.locale';
  function resolveLocale(saved, languages = []) {
    if (supported.includes(saved)) return saved;
    return /^zh(?:-|$)/i.test(languages[0] || '') ? 'zh-CN' : 'en-US';
  }
  function create({storage, languages = []} = {}) {
    let saved;
    try { saved = storage?.getItem(storageKey); } catch (_) { /* Storage may be disabled. */ }
    let locale = resolveLocale(saved, languages);
    function t(source, params = {}) {
      const copy = locale === 'en-US' ? (translations[source] ?? source) : source;
      return copy.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
    }
    return {
      get locale() { return locale; },
      setLocale(value) {
        if (!supported.includes(value)) return false;
        locale = value;
        try { storage?.setItem(storageKey, value); } catch (_) { /* Continue without persistence. */ }
        return true;
      },
      t,
      providerText(value) { return locale === 'zh-CN' ? (providerChinese[value] ?? value) : value; },
      errorText(error) {
        if (error?.name === 'TypeError') return t('无法连接本机面板，请确认服务仍在运行。');
        const message = error?.message || '';
        const source = errorSources[message]
          || (/^(Unknown (secret|non-secret) fields|Connection (secret|setting)|Unknown connection provider|Invalid connection profile|A profile cannot|Connection profile label is ambiguous)/.test(message) ? '连接参数无效，请检查字段内容与长度。' : null)
          || (/pricing|margin|multiplier|finite|fee_rate|return_rate|operating_rate|divisor/i.test(message) ? '定价参数无效，请检查数值范围与费率合计。' : null)
          || '请求未完成，请检查输入并确认本机服务仍在运行。';
        return t(source);
      },
      money(value) {
        return typeof value === 'number' && Number.isFinite(value)
          ? new Intl.NumberFormat(locale, {style:'currency', currency:'USD', currencyDisplay:'narrowSymbol', minimumFractionDigits:2, maximumFractionDigits:2}).format(value) : '—';
      },
      percent(value) {
        return typeof value === 'number' && Number.isFinite(value)
          ? new Intl.NumberFormat(locale, {style:'percent', minimumFractionDigits:1, maximumFractionDigits:1}).format(value) : '—';
      }
    };
  }
  const api = {translations, providerChinese, resolveLocale, create};
